#String Basics in Python

Hobby = "Badminton" #string variable

Achievement = """
I have won the Tournament in Gensan.
I have also represented my school in the inter-school competition.
""" #multiline string variable

Medals = "Gold \nSilver \nBronze" #string variable

print(len(Hobby)) #prints the length of the string variable
print(len(Achievement)) #prints the length of the multiline string variable
print(Hobby[0]) #prints the first character of the string variable
print(Achievement[0]) #prints the first character of the multiline string variable
print(Hobby[0:4]) #prints the first four characters of the string variable
print(Medals)
