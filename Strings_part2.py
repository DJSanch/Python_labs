first = "Daniel" #string variable
last = "Sanchez" #string variable
full = f"{first} {last}" #string variable using f-string


print(full) #prints the full name using f-string
print(first + " " + last) #prints the full name using concatenation
print(first, last) #prints the full name using comma separation

print(first.upper()) #prints the first name in uppercase
print(last.lower()) #prints the last name in lowercase
